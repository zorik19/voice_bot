from __future__ import annotations

import re

from num2words import num2words

# Формат Яндекса: '+' перед ударной гласной
STRESS = {
    "осаго": "ос+аго",
    "каско": "к+аско",
    "полис": "п+олис",
    "полиса": "п+олиса",
    "полису": "п+олису",
    "страховка": "страх+овка",
    "договор": "догов+ор",
    "рубль": "р+убль",
    "рубля": "рубл+я",
    "рублю": "рубл+ю",
    "рублей": "рубл+ей",
    "рублям": "рубл+ям",
    "рублями": "рубл+ями",
    "рублях": "рубл+ях",
    "рубли": "рубл+и",
}

ABBREV = {
    "кбм": "ка бэ эм",
    "л.с.": "лошадиных сил",
    "руб.": "рублей",
    "₽": "рублей",
    "%": "процентов",
}

_NUM_RE = re.compile(r"\d(?:[\d\s]*\d)?")  # без хвостового \s* — иначе "300 рублей" -> "тристарублей"

# LLM иногда пишет себе сценарную ремарку прямо в реплике — "(паузы для
# подтверждения)", "[клиент кладёт трубку]" — промпт это запрещает, но
# не гарантированно: если такое проскочило, это НЕЛЬЗЯ озвучивать буквально,
# поэтому режем на уровне кода, а не только просьбой в системном промпте.
_STAGE_DIRECTION_RE = re.compile(r"[(\[{][^)\]}]*[)\]}]")


def _strip_stage_directions(text: str) -> str:
    text = _STAGE_DIRECTION_RE.sub(" ", text)
    return re.sub(r"\s+", " ", text).strip()

# Дата "22 августа" читается порядковым числительным в родительном падеже
# ("двадцать второго"), а не количественным ("двадцать два") — общий
# конвертер чисел этого не знает, поэтому даты разбираем отдельно и раньше.
_DAY_ORDINAL_RU = {
    1: "первого", 2: "второго", 3: "третьего", 4: "четвёртого", 5: "пятого",
    6: "шестого", 7: "седьмого", 8: "восьмого", 9: "девятого", 10: "десятого",
    11: "одиннадцатого", 12: "двенадцатого", 13: "тринадцатого", 14: "четырнадцатого",
    15: "пятнадцатого", 16: "шестнадцатого", 17: "семнадцатого", 18: "восемнадцатого",
    19: "девятнадцатого", 20: "двадцатого", 21: "двадцать первого", 22: "двадцать второго",
    23: "двадцать третьего", 24: "двадцать четвёртого", 25: "двадцать пятого",
    26: "двадцать шестого", 27: "двадцать седьмого", 28: "двадцать восьмого",
    29: "двадцать девятого", 30: "тридцатого", 31: "тридцать первого",
}
_MONTHS_GEN = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)
_DATE_RE = re.compile(r"\b(\d{1,2})\s+(" + "|".join(_MONTHS_GEN) + r")\b")


def _date_to_words(m: re.Match) -> str:
    ordinal = _DAY_ORDINAL_RU.get(int(m.group(1)))
    return f"{ordinal} {m.group(2)}" if ordinal else m.group(0)


def _num_to_words(m: re.Match) -> str:
    digits = m.group().replace(" ", "")
    try:
        return num2words(int(digits), lang="ru")
    except (ValueError, OverflowError):
        return m.group()


def normalize_for_tts(text: str) -> str:
    """Числа прописью, аббревиатуры, ударения — страховка от '7128 руб.' в озвучке."""
    text = _strip_stage_directions(text)
    for k, v in ABBREV.items():
        text = re.sub(re.escape(k), v, text, flags=re.IGNORECASE)
    text = _DATE_RE.sub(_date_to_words, text)
    text = _NUM_RE.sub(_num_to_words, text)

    def _stress(m: re.Match) -> str:
        return STRESS[m.group().lower()]

    pattern = r"\b(" + "|".join(STRESS) + r")\b"
    return re.sub(pattern, _stress, text, flags=re.IGNORECASE)